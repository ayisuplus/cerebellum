#[cfg(test)]
mod tests {
    use std::fs;
    use std::path::PathBuf;

    #[test]
    fn exported_schemas_match_on_disk_files() {
        let schemas_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
            .join("..")
            .join("..")
            .join("schemas");
        for (name, generated) in super::schema_exports().unwrap() {
            let path = schemas_dir.join(name);
            let on_disk: serde_json::Value = serde_json::from_str(
                &fs::read_to_string(&path)
                    .unwrap_or_else(|error| panic!("cannot read {}: {error}", path.display())),
            )
            .unwrap_or_else(|error| panic!("cannot parse {}: {error}", path.display()));
            assert_eq!(
                on_disk, generated,
                "schemas/{name} is stale; regenerate with `cerebellum export-schemas schemas`"
            );
        }
    }
}
